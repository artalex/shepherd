#!/usr/bin/env python3
"""Generates the launcher icon layers from one geometry: edit this script, not the XML.

A shepherd's crook (the app is Shepherd) behind three panes in the agent status colours: amber waits for an
answer, blue works, green is done; the front pane shows a prompt. The colour layer draws the gaps between the
shapes as strokes in the background colour. The monochrome layer (themed icons) has a single colour, so it draws
outlines and clips each shape by the one in front of it. The notification icon is the monochrome drawing cropped
to its bounds at 24 dp.

Usage: scripts/launcher_icon.py [--preview icon.html]
The preview shows the icon in round and squircle masks and the 66 dp safe zone; render it with
google-chrome --headless --screenshot=icon.png file://$PWD/icon.html
"""

import argparse
from pathlib import Path

DRAWABLE = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

# The app's status hues (theme/); the background is @color/ic_launcher_background.
BACKGROUND = "#161B22"
AMBER, BLUE, GREEN = "#F2B84B", "#7CB8F5", "#7BD88F"
CROOK_COLOUR, PROMPT_COLOUR = "#EDE6D6", "#0F1215"

# Geometry in the 108 dp canvas, before the transform below.
CROOK = "M73,75 L73,38 A10,10 0 0 0 53,38 L53,43"
PANES = [(36, 38, AMBER), (30.5, 46.5, BLUE), (25, 55, GREEN)]  # x, y, colour; back to front
PANE_W, PANE_H, PANE_R = 31, 24, 4.5
PROMPT = ["M31.5,62 L37,66.8 L31.5,71.6", "M40,71.6 L47.5,71.6"]
GAP = 3  # colour: background stroke around a pane; monochrome: how far the shape behind is clipped

# The outline version is the larger one: its bounding box is centred and scaled into the 66 dp safe zone.
PIVOT, SCALE, SHIFT = (49.75, 52.75), 0.92, (4.25, 1.25)

# The notification icon's viewport: a square around the centre that holds the drawing (about 48 x 51 after the
# transform), so it fills the status bar icon.
NOTIFICATION_CROP = 54


def num(v: float) -> str:
    return f"{v:g}"


def rounded_rect(x: float, y: float, w: float, h: float, r: float, clockwise: bool = True) -> str:
    a = f"A{num(r)},{num(r)} 0 0 {1 if clockwise else 0}"
    if clockwise:
        return (
            f"M{num(x + r)},{num(y)} H{num(x + w - r)} {a} {num(x + w)},{num(y + r)} V{num(y + h - r)} "
            f"{a} {num(x + w - r)},{num(y + h)} H{num(x + r)} {a} {num(x)},{num(y + h - r)} V{num(y + r)} "
            f"{a} {num(x + r)},{num(y)} Z"
        )
    return (
        f"M{num(x + r)},{num(y)} {a} {num(x)},{num(y + r)} V{num(y + h - r)} {a} {num(x + r)},{num(y + h)} "
        f"H{num(x + w - r)} {a} {num(x + w)},{num(y + h - r)} V{num(y + r)} {a} {num(x + w - r)},{num(y)} Z"
    )


def pane(i: int) -> str:
    x, y, _ = PANES[i]
    return rounded_rect(x, y, PANE_W, PANE_H, PANE_R)


def all_but_pane(i: int) -> str:
    """The canvas minus pane i grown by GAP: the inner contour runs the other way, so non-zero winding cuts it out."""
    x, y, _ = PANES[i]
    inner = rounded_rect(x - GAP, y - GAP, PANE_W + 2 * GAP, PANE_H + 2 * GAP, PANE_R + GAP, clockwise=False)
    return f"M0,0 H108 V108 H0 Z {inner}"


def element(tag: str, attrs: dict[str, str], indent: int, children: list[str] | None = None) -> str:
    pad = " " * indent
    lines = [f"{pad}<{tag}"] + [f'{pad}    android:{k}="{v}"' for k, v in attrs.items()]
    if children is None:
        return "\n".join(lines) + " />\n"
    return "\n".join(lines) + ">\n" + "".join(children) + f"{pad}</{tag}>\n"


def stroke(path: str, colour: str, width: float, indent: int) -> str:
    attrs = {"pathData": path, "strokeColor": colour, "strokeWidth": num(width), "strokeLineCap": "round", "strokeLineJoin": "round"}
    return element("path", attrs, indent)


def vector(comment: str, children: list[str], size: int = 108, crop: float | None = None) -> str:
    """The layer in the 108 dp canvas; with [crop], only the square of that side around the centre, at [size] dp."""
    group = {"pivotX": num(PIVOT[0]), "pivotY": num(PIVOT[1]), "scaleX": num(SCALE), "scaleY": num(SCALE), "translateX": num(SHIFT[0]), "translateY": num(SHIFT[1])}
    viewport = crop or 108
    body = element("group", group, 8 if crop else 4, children)
    if crop:
        body = element("group", {"translateX": num((viewport - 108) / 2), "translateY": num((viewport - 108) / 2)}, 4, [body])
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/launcher_icon.py: edit the script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
        f'    android:viewportWidth="{num(viewport)}"\n    android:viewportHeight="{num(viewport)}">\n'
        f"    <!-- {comment} -->\n" + body + "</vector>\n"
    )


def foreground() -> str:
    children = [stroke(CROOK, CROOK_COLOUR, 6, 8)]
    for i, (_, _, colour) in enumerate(PANES):
        attrs = {"pathData": pane(i), "fillColor": colour, "strokeColor": "@color/ic_launcher_background", "strokeWidth": num(GAP)}
        children.append(element("path", attrs, 8))
    children += [stroke(p, PROMPT_COLOUR, 3.2, 8) for p in PROMPT]
    return vector("Gaps between the shapes are strokes in the background colour.", children)


def outlines(indent: int) -> list[str]:
    """The drawing in one colour: each shape clipped by the one in front of it."""
    white = "#FFFFFFFF"
    children = [
        element("group", {}, indent, [element("clip-path", {"pathData": all_but_pane(front)}, indent + 4), stroke(path, white, width, indent + 4)])
        for front, path, width in [(0, CROOK, 6), (1, pane(0), 3), (2, pane(1), 3)]
    ]
    children.append(stroke(pane(2), white, 3, indent))
    children += [stroke(p, white, 3.2, indent) for p in PROMPT]
    return children


def monochrome() -> str:
    return vector("One colour can't draw gaps: each shape is clipped by the one in front of it.", outlines(8))


def notification() -> str:
    return vector("The monochrome layer cropped to the drawing; Android paints it in the notification colour.", outlines(12), size=24, crop=NOTIFICATION_CROP)


def svg(themed: bool, fg: str = "", bg: str = BACKGROUND) -> str:
    transform = f"translate({num(PIVOT[0] + SHIFT[0])} {num(PIVOT[1] + SHIFT[1])}) scale({num(SCALE)}) translate({num(-PIVOT[0])} {num(-PIVOT[1])})"
    round_ = 'fill="none" stroke-linecap="round" stroke-linejoin="round"'
    out = [f'<rect width="108" height="108" fill="{bg}"/><g transform="{transform}">']
    if themed:
        for front, path, width in [(0, CROOK, 6), (1, pane(0), 3), (2, pane(1), 3)]:
            out.append(f'<clipPath id="c{front}"><path d="{all_but_pane(front)}"/></clipPath>')
            out.append(f'<path clip-path="url(#c{front})" d="{path}" stroke="{fg}" stroke-width="{width}" {round_}/>')
        out.append(f'<path d="{pane(2)}" stroke="{fg}" stroke-width="3" {round_}/>')
        out += [f'<path d="{p}" stroke="{fg}" stroke-width="3.2" {round_}/>' for p in PROMPT]
    else:
        out.append(f'<path d="{CROOK}" stroke="{CROOK_COLOUR}" stroke-width="6" {round_}/>')
        out += [f'<path d="{pane(i)}" fill="{c}" stroke="{BACKGROUND}" stroke-width="{GAP}"/>' for i, (_, _, c) in enumerate(PANES)]
        out += [f'<path d="{p}" stroke="{PROMPT_COLOUR}" stroke-width="3.2" {round_}/>' for p in PROMPT]
    return "".join(out) + "</g>"


def preview() -> str:
    # The copies share clip-path ids; every copy has the same geometry, so whichever one an id resolves to fits.
    rows = []
    for name, body in [("colour", svg(False)), ("themed", svg(True, "#C2E7FF", "#0B2A44")), ("themed, light", svg(True, "#0B2A44", "#D3E3FD"))]:
        cells = [
            f'<span style="display:inline-block;margin:8px;width:{s}px;height:{s}px;border-radius:{shape};overflow:hidden">'
            f'<svg width="{s}" height="{s}" viewBox="18 18 72 72">{body}</svg></span>'
            for shape in ["50%", "30%"]
            for s in [216, 96, 48]
        ]
        rows.append(f'<div>{"".join(cells)}<b>{name}</b></div>')
    safe = '<circle cx="54" cy="54" r="33" fill="none" stroke="red" stroke-width="0.4"/>'
    rows += [f'<svg width="324" height="324" viewBox="0 0 108 108">{body}{safe}</svg>' for body in [svg(False), svg(True, "#C2E7FF", "#0B2A44")]]
    return '<!doctype html><meta charset="utf-8"><body style="background:#1b2430;color:#ccc;font:14px sans-serif">' + "".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", type=Path, help="also write an HTML preview here")
    args = parser.parse_args()
    (DRAWABLE / "ic_launcher_foreground.xml").write_text(foreground())
    (DRAWABLE / "ic_launcher_monochrome.xml").write_text(monochrome())
    (DRAWABLE / "ic_notification.xml").write_text(notification())
    if args.preview:
        args.preview.write_text(preview())


if __name__ == "__main__":
    main()
